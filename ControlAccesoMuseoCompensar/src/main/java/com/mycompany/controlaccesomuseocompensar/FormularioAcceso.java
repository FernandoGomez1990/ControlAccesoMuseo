    private void CbxCategoriaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_CbxCategoriaActionPerformed
        // TODO add your handling code here:
        if (TxtEdad.getText().isEmpty()) {
        TxtALiquidacion.setText("Por favor ingrese la edad.");
        return;
        }
        
        int edad = Integer.parseInt(TxtEdad.getText());
        String categoria = CbxCategoria.getSelectedItem().toString();                
        //double tarifa = 0; Se pasa de variable local a objeto.
        
        if(edad < 18){
            tarifa = 5000;
        }else {
            switch (categoria) {
                case "NO AFILIADO":
                    tarifa = 30000;
                    break;
                case "CATEGORÍA A":
                    tarifa = 30000 * 0.85;
                    break;
                case "CATEGORÍA B":
                    tarifa = 30000 * 0.70;
                    break;
                case "CATEGORÍA C":
                    tarifa = 30000 * 0.50;
                    break;
            }
        }
        
        TxtALiquidacion.setText(String.format(
                "El valor a pagar es $%,.2f", tarifa));
    }//GEN-LAST:event_CbxCategoriaActionPerformed

