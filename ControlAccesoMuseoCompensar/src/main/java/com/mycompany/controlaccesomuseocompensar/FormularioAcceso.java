    private void BtnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnRegistrarActionPerformed
        // TODO add your handling code here:
        try{
        String nombre = TxtNombre.getText();
        String identidad = TxtIdentidad.getText();
        int edad = Integer.parseInt(TxtEdad.getText());
        String categoria = CbxCategoria.getSelectedItem().toString();
        control.registrarVisitantes(nombre, identidad, edad, categoria, tarifa);
        } catch (NumberFormatException e) {

        TxtALiquidacion.setText("Debe diligenciar todos los datos");
        } finally {

        System.out.println("Proceso de registro finalizado.");

        }        
    }//GEN-LAST:event_BtnRegistrarActionPerformed

